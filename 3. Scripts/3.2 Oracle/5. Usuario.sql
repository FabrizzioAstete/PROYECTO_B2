-- Criterio unificado: identificadores SIN comillas (MAYÚSCULAS). Solo las contraseñas van entre comillas dobles.
CREATE ROLE ROL_OPERADOR;
BEGIN
  FOR T IN (SELECT TABLE_NAME FROM DBA_TABLES WHERE OWNER = 'MYPE_OWNER') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT, INSERT, UPDATE ON MYPE_OWNER.' || T.TABLE_NAME || ' TO ROL_OPERADOR';
  END LOOP;
END;
/
GRANT EXECUTE ON MYPE_OWNER.SP_RECIBIR_ORDEN, MYPE_OWNER.SP_GENERAR_ALERTA, MYPE_OWNER.SP_ATENDER_ALERTA, MYPE_OWNER.FN_TOTAL_COMPRAS_MES, MYPE_OWNER.FN_ALERTAS_ACTIVAS TO ROL_OPERADOR;
CREATE USER MYPE_OPERADOR IDENTIFIED BY "Cambiar_Operador#2026" DEFAULT TABLESPACE USERS PROFILE PROF_MYPE;
GRANT CREATE SESSION, ROL_OPERADOR TO MYPE_OPERADOR;

CREATE ROLE ROL_ANALISTA;
BEGIN
  FOR T IN (SELECT TABLE_NAME FROM DBA_TABLES WHERE OWNER = 'MYPE_OWNER') LOOP
    EXECUTE IMMEDIATE 'GRANT SELECT ON MYPE_OWNER.' || T.TABLE_NAME || ' TO ROL_ANALISTA';
  END LOOP;
END;
/
GRANT EXECUTE ON MYPE_OWNER.FN_TOTAL_COMPRAS_MES TO ROL_ANALISTA;
CREATE USER MYPE_ANALISTA IDENTIFIED BY "Cambiar_Analista#2026" DEFAULT TABLESPACE USERS PROFILE PROF_MYPE;
GRANT CREATE SESSION, ROL_ANALISTA TO MYPE_ANALISTA;

-- Soporte: SOLO vista V_ALERTA_SOPORTE (se prefiere vista + trigger al GRANT por columna; TRG_ALERTA_SOLO_ESTADO refuerza la regla)
CREATE ROLE ROL_SOPORTE;
GRANT SELECT, UPDATE ON MYPE_OWNER.V_ALERTA_SOPORTE TO ROL_SOPORTE;
GRANT SELECT ON MYPE_OWNER.MOVIMIENTO_INVENTARIO TO ROL_SOPORTE;
CREATE USER MYPE_SOPORTE IDENTIFIED BY "Cambiar_Soporte#2026" DEFAULT TABLESPACE USERS PROFILE PROF_MYPE;
GRANT CREATE SESSION, ROL_SOPORTE TO MYPE_SOPORTE;
