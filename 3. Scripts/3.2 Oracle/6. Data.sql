-- MypeInventario | Oracle 19c/21c | Paso 6: datos sintéticos (500 = 100 por participante x 5). Conectado como MYPE_OWNER, esquema limpio.
-- Los ids 1..500 coinciden con los de PostgreSQL (referencias lógicas entre motores).
INSERT INTO ORDEN_COMPRA (ID_COMERCIANTE, ID_PROVEEDOR, FE_ORDEN, FE_RECEPCION, TOTAL, ESTADO)
SELECT LEVEL, LEVEL, SYSTIMESTAMP - NUMTODSINTERVAL(LEVEL*9,'HOUR'),
       CASE WHEN MOD(LEVEL,2)=0 THEN SYSTIMESTAMP - NUMTODSINTERVAL(LEVEL*9-5,'HOUR') END, 0,
       CASE WHEN MOD(LEVEL,2)=0 THEN 'RECIBIDA' ELSE 'ENVIADA' END
FROM DUAL CONNECT BY LEVEL <= 500;
INSERT INTO DETALLE_ORDEN_COMPRA (ID_ORDEN, ID_SKU, CANTIDAD, COSTO_UNITARIO, SUBTOTAL)
SELECT LEVEL, LEVEL, 10 + MOD(LEVEL,40), 10 + MOD(LEVEL,20), 0 FROM DUAL CONNECT BY LEVEL <= 500;
UPDATE ORDEN_COMPRA O SET TOTAL = (SELECT SUM(SUBTOTAL) FROM DETALLE_ORDEN_COMPRA D WHERE D.ID_ORDEN = O.ID_ORDEN);
INSERT INTO PAGO_VENTA (ID_VENTA, ID_COMERCIANTE, METODO_PAGO, MONTO, NRO_OPERACION, FE_PAGO, ESTADO)
SELECT LEVEL, LEVEL, CASE MOD(LEVEL,5) WHEN 0 THEN 'EFECTIVO' WHEN 1 THEN 'YAPE' WHEN 2 THEN 'PLIN' WHEN 3 THEN 'TARJETA' ELSE 'TRANSFERENCIA' END,
       15 + MOD(LEVEL,30), 'OP' || LPAD(LEVEL,8,'0'), SYSTIMESTAMP - NUMTODSINTERVAL(LEVEL*7,'HOUR'),
       CASE WHEN MOD(LEVEL,25)=0 THEN 'PENDIENTE' ELSE 'CONFIRMADO' END
FROM DUAL CONNECT BY LEVEL <= 500;
-- Kardex repartido en varios meses para ver las particiones por intervalo
INSERT INTO MOVIMIENTO_INVENTARIO (ID_SKU, ID_ORDEN, ID_VENTA, TIPO_MOVIMIENTO, MOTIVO, CANTIDAD, FE_MOVIMIENTO, OBSERVACION)
SELECT LEVEL, CASE WHEN MOD(LEVEL,2)=0 THEN LEVEL END, CASE WHEN MOD(LEVEL,2)=1 THEN LEVEL END,
       CASE WHEN MOD(LEVEL,2)=0 THEN 'ENTRADA' ELSE 'SALIDA' END, CASE WHEN MOD(LEVEL,2)=0 THEN 'COMPRA' ELSE 'VENTA' END,
       1 + MOD(LEVEL,5), SYSTIMESTAMP - NUMTODSINTERVAL(LEVEL*20,'HOUR'), 'Movimiento sintético ' || LEVEL
FROM DUAL CONNECT BY LEVEL <= 500;
INSERT INTO ALERTA_REABASTECIMIENTO (ID_SKU, ID_COMERCIANTE, FE_GENERACION, STOCK_AL_GENERAR, STOCK_MINIMO, CANAL_NOTIFICACION, ESTADO)
SELECT LEVEL, LEVEL, SYSTIMESTAMP - NUMTODSINTERVAL(LEVEL,'HOUR'), MOD(LEVEL,6), 5,
       CASE MOD(LEVEL,3) WHEN 0 THEN 'PUSH' WHEN 1 THEN 'WHATSAPP' ELSE 'EMAIL' END, CASE WHEN MOD(LEVEL,4)=0 THEN 'ATENDIDA' ELSE 'PENDIENTE' END
FROM DUAL CONNECT BY LEVEL <= 500;
INSERT INTO AUDITORIA_PRECIO (ID_SKU, PRECIO_ANTERIOR, PRECIO_NUEVO, MOTIVO)
SELECT LEVEL, 15 + MOD(LEVEL,30), 16 + MOD(LEVEL,30), 'Ajuste sintético' FROM DUAL CONNECT BY LEVEL <= 500;
COMMIT;
