-- F1. Total comprado a proveedores en un mes
CREATE OR REPLACE FUNCTION FN_TOTAL_COMPRAS_MES(P_ID_COMERCIANTE IN NUMBER, P_ANIO IN NUMBER, P_MES IN NUMBER) RETURN NUMBER IS
  V_TOTAL NUMBER;
BEGIN
  SELECT NVL(SUM(TOTAL),0) INTO V_TOTAL FROM ORDEN_COMPRA
   WHERE ID_COMERCIANTE = P_ID_COMERCIANTE AND ESTADO = 'RECIBIDA'
     AND FE_ORDEN >= TO_TIMESTAMP(P_ANIO||'-'||LPAD(P_MES,2,'0')||'-01','YYYY-MM-DD')
     AND FE_ORDEN <  ADD_MONTHS(TO_TIMESTAMP(P_ANIO||'-'||LPAD(P_MES,2,'0')||'-01','YYYY-MM-DD'),1);
  RETURN V_TOTAL;
END;
/
-- Uso: SELECT FN_TOTAL_COMPRAS_MES(1,2026,10) FROM DUAL;

-- F2. Cantidad de alertas activas
CREATE OR REPLACE FUNCTION FN_ALERTAS_ACTIVAS(P_ID_COMERCIANTE IN NUMBER DEFAULT NULL) RETURN NUMBER IS V_N NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_N FROM ALERTA_REABASTECIMIENTO
   WHERE ESTADO IN ('PENDIENTE','ENVIADA') AND (P_ID_COMERCIANTE IS NULL OR ID_COMERCIANTE = P_ID_COMERCIANTE);
  RETURN V_N;
END;
/
-- Uso: SELECT FN_ALERTAS_ACTIVAS(NULL) FROM DUAL;

-- T1. Trigger: subtotal de línea de orden = cantidad x costo (el total de la orden se consolida en SP_RECIBIR_ORDEN;
--     un trigger de fila no puede consultar su propia tabla: ORA-04091 tabla mutante)
CREATE OR REPLACE TRIGGER TRG_DOC_SUBTOTAL BEFORE INSERT OR UPDATE OF CANTIDAD, COSTO_UNITARIO ON DETALLE_ORDEN_COMPRA
FOR EACH ROW
BEGIN
  :NEW.SUBTOTAL := ROUND(:NEW.CANTIDAD * :NEW.COSTO_UNITARIO, 2);
END;
/
-- P1. Recibir una orden: marca RECIBIDA, consolida el TOTAL y registra una ENTRADA de kardex por línea (transacción atómica)
CREATE OR REPLACE PROCEDURE SP_RECIBIR_ORDEN(P_ID_ORDEN IN NUMBER) IS
BEGIN
  UPDATE ORDEN_COMPRA SET ESTADO = 'RECIBIDA', FE_RECEPCION = SYSTIMESTAMP,
         TOTAL = (SELECT NVL(SUM(SUBTOTAL),0) FROM DETALLE_ORDEN_COMPRA WHERE ID_ORDEN = P_ID_ORDEN)
   WHERE ID_ORDEN = P_ID_ORDEN AND ESTADO IN ('BORRADOR','ENVIADA');
  IF SQL%ROWCOUNT = 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'Orden inexistente o ya recibida/anulada: ' || P_ID_ORDEN);
  END IF;
  INSERT INTO MOVIMIENTO_INVENTARIO (ID_SKU, ID_ORDEN, TIPO_MOVIMIENTO, MOTIVO, CANTIDAD, OBSERVACION)
  SELECT ID_SKU, ID_ORDEN, 'ENTRADA', 'COMPRA', CANTIDAD, 'Recepción de orden ' || ID_ORDEN
    FROM DETALLE_ORDEN_COMPRA WHERE ID_ORDEN = P_ID_ORDEN;
  COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK; RAISE;
END;
/
-- Uso: EXEC SP_RECIBIR_ORDEN(1);

-- P2. Generar alerta (evita duplicar si ya existe una activa para el SKU)
CREATE OR REPLACE PROCEDURE SP_GENERAR_ALERTA(P_ID_SKU IN NUMBER, P_ID_COMERCIANTE IN NUMBER, P_STOCK IN NUMBER, P_MINIMO IN NUMBER,
                                              P_CANAL IN VARCHAR2 DEFAULT 'PUSH') IS
  V_N NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_N FROM ALERTA_REABASTECIMIENTO WHERE ID_SKU = P_ID_SKU AND ESTADO IN ('PENDIENTE','ENVIADA');
  IF V_N = 0 AND P_STOCK <= P_MINIMO THEN
    INSERT INTO ALERTA_REABASTECIMIENTO (ID_SKU, ID_COMERCIANTE, STOCK_AL_GENERAR, STOCK_MINIMO, CANAL_NOTIFICACION)
    VALUES (P_ID_SKU, P_ID_COMERCIANTE, P_STOCK, P_MINIMO, P_CANAL);
  END IF;
END;
/
-- P3. Atender alerta
CREATE OR REPLACE PROCEDURE SP_ATENDER_ALERTA(P_ID_ALERTA IN NUMBER) IS
BEGIN
  UPDATE ALERTA_REABASTECIMIENTO SET ESTADO = 'ATENDIDA', FE_ATENCION = SYSTIMESTAMP
   WHERE ID_ALERTA = P_ID_ALERTA AND ESTADO IN ('PENDIENTE','ENVIADA');
  IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20001, 'Alerta no encontrada o ya atendida'); END IF;
END;
/
-- Siguiendo la observación del docente, el acceso de soporte NO se limita con GRANT por columna sino con una VISTA actualizable
-- (solo expone ESTADO y FE_ATENCION) + TRIGGER de defensa sobre la tabla base.
CREATE OR REPLACE VIEW V_ALERTA_SOPORTE AS
  SELECT ID_ALERTA, ID_SKU, ESTADO, FE_ATENCION FROM ALERTA_REABASTECIMIENTO;
CREATE OR REPLACE TRIGGER TRG_ALERTA_SOLO_ESTADO BEFORE UPDATE ON ALERTA_REABASTECIMIENTO FOR EACH ROW
BEGIN
  IF USER = 'MYPE_SOPORTE' AND (:NEW.ID_SKU <> :OLD.ID_SKU OR :NEW.STOCK_AL_GENERAR <> :OLD.STOCK_AL_GENERAR
     OR :NEW.STOCK_MINIMO <> :OLD.STOCK_MINIMO OR :NEW.ID_COMERCIANTE <> :OLD.ID_COMERCIANTE) THEN
    RAISE_APPLICATION_ERROR(-20010, 'MYPE_SOPORTE solo puede modificar ESTADO y FE_ATENCION');
  END IF;
END;
/
